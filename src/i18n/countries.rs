pub fn translate_country_entry(entry: &str) -> Cow<'_, str> {
	if !crate::i18n::is_indonesian() {
		return Cow::Borrowed(entry);
	}
	if let Some((name, suffix)) = entry.rsplit_once(" (+") {
		let translated = translate_country_name(name);
		if translated != name {
			return Cow::Owned(format!("{translated} (+{suffix}"));
		}
	} else {
		let translated = translate_country_name(entry);
		if translated != entry {
			return Cow::Borrowed(translated);
		}
	}
	Cow::Borrowed(entry)
}
