#!/usr/bin/env python3
"""Generates src/phone_data.rs from libphonenumber's PhoneNumberMetadata.xml.

Usage: tools/gen_phone_data.py path/to/PhoneNumberMetadata.xml > src/phone_data.rs

Keeps only what src/phone.rs needs to tell whether a number is valid and to
write it in international format: per region its number-type patterns and
lengths, and per calling code the international formats of its main region.
"""

import re
import sys
import xml.etree.ElementTree as ET

TYPES = ["fixedLine", "mobile", "pager", "tollFree", "premiumRate", "sharedCost", "personalNumber", "voip", "uan",
         "voicemail"]


def squeeze(text):
    return re.sub(r"\s", "", text or "")


def lengths(desc):
    """possibleLengths national="[4-6],8" -> sorted list of lengths."""
    el = desc.find("possibleLengths")
    if el is None or not el.get("national"):
        return []
    out = set()
    for part in el.get("national").split(","):
        m = re.fullmatch(r"\[(\d+)-(\d+)\]", part)
        if m:
            out.update(range(int(m.group(1)), int(m.group(2)) + 1))
        else:
            out.add(int(part))
    return sorted(out)


def rust_str(s):
    assert '"' not in s
    return 'r"' + s + '"'


def desc(d):
    return "(%s, &%s)" % (rust_str(squeeze(d.find("nationalNumberPattern").text)), lengths(d))


root = ET.parse(sys.argv[1]).getroot()
by_code = {}
for te in root.find("territories"):
    code = int(te.get("countryCode"))
    by_code.setdefault(code, [])
    if te.get("mainCountryForCode") == "true":
        by_code[code].insert(0, te)
    else:
        by_code[code].append(te)

out = []
out.append("// Generated by tools/gen_phone_data.py from libphonenumber's PhoneNumberMetadata.xml. Don't edit.\n")
out.append("use crate::phone::{Country, Format, Region};\n")
out.append("pub(crate) static COUNTRIES: &[Country] = &[")
for code in sorted(by_code):
    regions = []
    for te in by_code[code]:
        general = te.find("generalDesc")
        types = []
        for t in TYPES:
            d = te.find(t)
            if d is not None and d.find("nationalNumberPattern") is not None and desc(d) not in types:
                types.append(desc(d))
        leading = te.get("leadingDigits")
        regions.append("Region { leading: %s, general: %s, types: &[%s] }" % (
            "Some(%s)" % rust_str(squeeze(leading)) if leading else "None", desc(general), ", ".join(types)))
    main = by_code[code][0]
    formats = []
    af = main.find("availableFormats")
    for nf in ([] if af is None else af.findall("numberFormat")):
        intl = nf.find("intlFormat")
        text = nf.find("format").text if intl is None else intl.text
        if text == "NA":
            continue
        groups = re.findall(r"\(\\d(?:\{(\d+)(?:,(\d+))?\})?\)", nf.get("pattern"))
        assert "".join("(\\d%s)" % ("{%s%s}" % (a, "," + b if b else "") if a else "") for a, b in groups) == nf.get("pattern"), nf.get("pattern")
        groups = [(int(a or 1), int(b or a or 1)) for a, b in groups]
        lead = nf.findall("leadingDigits")
        formats.append("Format { leading: %s, groups: &%s, format: %s }" % (
            "Some(%s)" % rust_str(squeeze(lead[-1].text)) if lead else "None",
            "[" + ", ".join("(%d, %d)" % g for g in groups) + "]", rust_str(text)))
    out.append("\tCountry {\n\t\tcode: %d,\n\t\tnational_prefix: %s,\n\t\tregions: &[%s],\n\t\tformats: &[%s],\n\t}," % (
        code, rust_str(main.get("nationalPrefix") or ""), ", ".join(regions), ", ".join(formats)))
out.append("];")
print("\n".join(out))
